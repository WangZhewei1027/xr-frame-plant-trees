const { build } = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'miniprogram/labs/xr-three/vendor');
async function main() {
  fs.mkdirSync(out, { recursive: true });
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['scripts/xr-three/entry.mjs'],
    outfile: path.join(out, 'three.js'), bundle: true, format: 'cjs',
    platform: 'neutral', mainFields: ['module', 'main'], target: 'es2018',
    minify: true, legalComments: 'eof', metafile: true,
    inject: ['scripts/xr-three/text-decoder.mjs'],
  });
  const version = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/three/package.json'))).version;
  fs.copyFileSync(path.join(root, 'node_modules/three/LICENSE'), path.join(out, 'THREE-LICENSE.txt'));
  fs.copyFileSync(path.join(root, 'node_modules/abort-controller/LICENSE'), path.join(out, 'ABORT-CONTROLLER-LICENSE.txt'));
  fs.copyFileSync(path.join(root, 'node_modules/event-target-shim/LICENSE'), path.join(out, 'EVENT-TARGET-SHIM-LICENSE.txt'));
  fs.writeFileSync(path.join(out, 'build-info.js'), 'module.exports = ' + JSON.stringify({
    package: 'three', version, bytes: fs.statSync(path.join(out, 'three.js')).size,
    source: `https://www.npmjs.com/package/three/v/${version}`,
    renderer: 'WebGLRenderer', webgl: 2,
    note: 'Generated by npm run build:xr-three-lab. No changes to Three.js source.',
  }, null, 2) + ';\n');
  console.log(`Built three@${version}: ${fs.statSync(path.join(out, 'three.js')).size} bytes; ${Object.keys(result.metafile.inputs).length} input modules`);
}
main().catch(e => { console.error(e); process.exitCode = 1; });
